"""ПР4, завдання 4: енергетичний баланс акумулятора 18650 для трьох режимів роботи."""
CAP_MAH = 3000          # акумулятор 18650
SCENARIOS = {
    # назва: (активний струм мА, тривалість активної фази с, період с, струм сну мА)
    "Зараз: постійно ввімкнений Wi-Fi, опитування кожні 3 с": (120, 3, 3, 120),
    "Сон між вимірами, вимір + MQTT раз на 60 с":            (120, 2, 60, 0.01),
    "Сон, вимір раз на 5 хв":                                (120, 2, 300, 0.01),
}
TARGET_DAYS = 30
print("Сценарій\tI акт, мА\tt акт, с\tПеріод, с\tI сну, мА\tСередній I, мА\tДнів роботи\tЦіль 30 дн.")
for name, (ia, ta, period, isl) in SCENARIOS.items():
    duty = min(ta / period, 1)
    avg = ia * duty + isl * (1 - duty)
    days = CAP_MAH / avg / 24
    print(f"{name}\t{ia}\t{ta}\t{period}\t{isl}\t{avg:.3f}\t{days:.1f}\t{'так' if days >= TARGET_DAYS else 'ні'}")
